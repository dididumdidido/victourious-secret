"""Turn a survey CSV export (e.g. from Formspree) into data/stats.js.

Usage:  python3 tools/make_stats.py survey-export.csv
Column names must match the survey's field names (status, experienced, reported,
leadership_help, had_lawyer, needs, safe_reporting, ...). Multi-select answers may be
separated by commas or semicolons.
"""
import csv, json, sys, datetime, re, pathlib

SINGLE = ["reported", "leadership_help", "had_lawyer"]
MULTI = ["experienced", "needs"]
CLIMATE = ["safe_reporting", "trust_command", "retaliation_protected", "know_outside_help"]

rows = list(csv.DictReader(open(sys.argv[1], newline="", encoding="utf-8-sig")))
rows = [r for r in rows if r.get("form", "survey") in ("survey", "")]
split = lambda v: [x.strip() for x in re.split(r"[;,]\s*(?=[A-Z])", v or "") if x.strip()]

out = {"isSample": False, "minResponses": 25, "updated": datetime.date.today().strftime("%B %-d, %Y"), "total": len(rows)}
for f in SINGLE:
    c = {}
    for r in rows:
        if r.get(f): c[r[f]] = c.get(r[f], 0) + 1
    out[f] = {"counts": c}
for f in MULTI:
    c, answered = {}, 0
    for r in rows:
        vals = split(r.get(f))
        if vals: answered += 1
        for v in vals: c[v] = c.get(v, 0) + 1
    out[f] = {"answered": answered, "counts": c}
out["climate"] = {}
for f in CLIMATE:
    c = {str(i): 0 for i in range(1, 6)}
    for r in rows:
        if r.get(f) in c: c[r[f]] += 1
    out["climate"][f] = c

dest = pathlib.Path(__file__).resolve().parent.parent / "data" / "stats.js"
dest.write_text("/* Generated by tools/make_stats.py — do not edit by hand. */\nwindow.STATS = " + json.dumps(out, indent=2) + ";\n")
print(f"Wrote {dest} from {len(rows)} responses" + ("" if len(rows) >= 25 else " — page will wait until 25 responses."))
